#!/usr/bin/env node
/**
 * Copies the ABIs Foundry just compiled into the shared package as typed TS consts.
 *
 * Run after any contract change: `pnpm abi`. Nothing hand-copies an ABI, so the app,
 * relayer, agent and indexer can never drift from the deployed contracts.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "contracts", "out");
const destDir = join(root, "packages", "shared", "src", "abi");

const CONTRACTS = [
  ["ThunaiVault", "ThunaiVault.sol"],
  ["ScamSignals", "ScamSignals.sol"],
  ["MockERC20", "MockERC20.sol"],
];

mkdirSync(destDir, { recursive: true });

const index = [
  "// Generated by scripts/sync-abis.mjs. Do not edit by hand.",
  "// Run `pnpm abi` after changing a contract.",
  "",
];

for (const [name, file] of CONTRACTS) {
  const artifactPath = join(outDir, file, `${name}.json`);
  let artifact;
  try {
    artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
  } catch {
    console.error(`! missing ${artifactPath} — run \`pnpm contracts:build\` first`);
    process.exit(1);
  }

  const body = `// Generated from contracts/out/${file}/${name}.json. Do not edit by hand.
export const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
  writeFileSync(join(destDir, `${name}.ts`), body);
  index.push(`export { ${name}Abi } from "./${name}";`);
  console.log(`  ${name} (${artifact.abi.length} entries)`);
}

writeFileSync(join(destDir, "index.ts"), `${index.join("\n")}\n`);
console.log("ABIs synced to packages/shared/src/abi");
